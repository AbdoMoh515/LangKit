export function checkGitAvailable(git) {
  const version = git.version();
  if (!version) {
    throw new LangError(
      'git is required but was not found on PATH.\n' +
      'install it first:\n' +
      '  windows: winget install --id Git.Git  (or https://git-scm.com/downloads)\n' +
      '  macos:   brew install git\n' +
      '  linux:   sudo apt install git   |   sudo dnf install git\n' +
      'then re-run "lang init --here". nothing was modified.'
    );
  }
  return version;
}

export function checkEmptyDir(root) {
  const entries = fs.readdirSync(root);
  if (entries.length > 0) {
    throw new LangError(
      `directory is not empty (found ${entries.length} entr${entries.length === 1 ? 'y' : 'ies'}). ` +
      '"lang init --here" expects an empty, new project folder. nothing was modified.'
    );
  }
}

export function checkNotNestedRepo(root, git) {
  const top = git.repoTopLevel();
  if (top) {
    throw new LangError(
      `this directory is inside an existing git repository (${top}). ` +
      'lang does not create nested repositories. run "lang init --here" in a fresh folder outside any repo. nothing was modified.'
    );
  }
}

export function initProject(root, { gitBin } = {}) {
  const git = createGitAdapter(root, { gitBin });
  checkGitAvailable(git);
  checkEmptyDir(root);
  checkNotNestedRepo(root, git);

  scaffoldInitialFiles(root);
  installTemplates(root);

  git.init();
  git.setLocalIdentityIfMissing('Lang Learner', 'learner@lang.local');
  git.add(TRACKED_PATHS);
  git.commit('chore(init): initialize lang project');
  return { root, branch: git.currentBranch() };
}
