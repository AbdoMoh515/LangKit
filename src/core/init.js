import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { LangError } from './errors.js';
import { LAYOUT, within, ensureDir, writeJson } from './paths.js';
import { emptyState, saveState } from './state.js';
import { emptyRegistry, saveRegistry } from './vocabulary.js';
import { createGitAdapter } from './git.js';
import { TRACKED_PATHS } from './paths.js';

const templatesDir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..', 'templates');

export function templateSource() {
  return path.join(templatesDir, 'opencode');
}

export function installTemplates(root) {
  const src = templateSource();
  if (!fs.existsSync(src)) throw new LangError(`templates not found at ${src}`);
  fs.cpSync(src, within(root, LAYOUT.opencodeDir), { recursive: true });
}

export function scaffoldInitialFiles(root) {
  ensureDir(within(root, LAYOUT.learnerDir));
  ensureDir(within(root, LAYOUT.vocabularyDir));
  ensureDir(within(root, LAYOUT.ankiDir));
  ensureDir(within(root, LAYOUT.phasesDir));
  saveState(root, emptyState());
  saveRegistry(root, emptyRegistry());
  if (!fs.existsSync(within(root, LAYOUT.planMd))) {
    fs.writeFileSync(within(root, LAYOUT.planMd), initialPlanMd(), 'utf8');
  }
  if (!fs.existsSync(within(root, LAYOUT.readmeMd))) {
    fs.writeFileSync(within(root, LAYOUT.readmeMd), learnerReadme(), 'utf8');
  }
}

function initialPlanMd() {
  return [
    '# Learning Plan',
    '',
    '> This plan is generated by the agent during `/lang-start`. It lists phases,',
    '> milestones, objectives, estimated effort, dependencies and exit criteria.',
    '> Until then, run `/lang-start` in OpenCode to set up your learner profile.',
    ''
  ].join('\n');
}

